def supported_venues() -> list[str]:
    return list(_VENUE_LATLON.keys())


def resolve_lat_lon(venue: str) -> tuple[float, float]:
    """場名から (lat, lon) を返す。未対応は日本語エラー。"""
    if not venue:
        raise WeatherFetchError("場名が指定されていません。")
    pair = _VENUE_LATLON.get(venue)
    if pair is None:
        raise WeatherFetchError(
            f"未対応の場名です: '{venue}'。対応場名: {', '.join(_VENUE_LATLON.keys())}"
        )
    return pair
